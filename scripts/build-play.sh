#!/usr/bin/env bash
# Builds the question bundles for /play/ (the live game with friends) from the subject question makers.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=public/play; mkdir -p "$OUT"
cat src/science/core.js src/science/gens.js src/science/long.js src/science/data.js src/shared/practice.js > "$OUT/sci.js"
cat src/maths/engine.js src/maths/simple.js src/maths/data.js src/maths/long.js src/shared/practice.js > "$OUT/maths.js"
# stamp the build so browsers fetch fresh bundles after a change
sed -i -E "s#<html lang=\"en\"( data-build=\"[0-9]+\")?>#<html lang=\"en\" data-build=\"$(date +%s)\">#" "$OUT/index.html"
# the same question makers as server modules: the Worker makes and marks every game question itself
mkdir -p src/gen
for f in maths sci; do
  { echo "// GENERATED by scripts/build-play.sh from the question makers, so the server can make and mark game questions. Don't edit."
    cat "$OUT/$f.js"; echo
    echo "export { pickPractice, asMCQ, makeQ, TOPIC_GENS, pick, TOPICS };"; } > "src/gen/$f-game.js"
done
echo "Built $OUT/sci.js and $OUT/maths.js (and src/gen/*-game.js for the server)"
